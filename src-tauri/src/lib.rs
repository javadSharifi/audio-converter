#[cfg(target_os = "android")]
#[no_mangle]
pub extern "C" fn Java_com_audioconverter_app_MainActivity_initNativePaths(
    mut env: jni::JNIEnv,
    _class: jni::objects::JClass,
    native_lib_dir: jni::objects::JString,
    cache_dir: jni::objects::JString,
) {
    if let Ok(vm) = env.get_java_vm() {
        android_fs::set_java_vm(vm);
    }
    // This is a Java-invoked native method, so FindClass resolves app classes
    // via MainActivity's classloader — the ONLY safe place to capture the
    // class reference for later use on background (attached) threads.
    android_fs::cache_main_activity_class(&mut env);
    if let Ok(dir) = env.get_string(&native_lib_dir) {
        let dir_str: String = dir.into();
        std::env::set_var("TAURI_ANDROID_NATIVE_LIB_DIR", &dir_str);
        log_info!("Android JNI: TAURI_ANDROID_NATIVE_LIB_DIR={}", dir_str);
    }
    if let Ok(dir) = env.get_string(&cache_dir) {
        let dir_str: String = dir.into();
        std::env::set_var("TAURI_ANDROID_CACHE_DIR", &dir_str);
        log_info!("Android JNI: TAURI_ANDROID_CACHE_DIR={}", dir_str);
    }
}

/// Registered by the Android runtime the moment `libaudio_converter.so` is
/// loaded — independent of MainActivity lifecycle, so the JNI bridge works
/// even if `initNativePaths` was never called (or failed) in Kotlin.
#[cfg(target_os = "android")]
#[no_mangle]
pub extern "system" fn JNI_OnLoad(
    vm: *mut jni::sys::JavaVM,
    _reserved: *mut std::ffi::c_void,
) -> jni::sys::jint {
    match unsafe { jni::JavaVM::from_raw(vm) } {
        Ok(vm) => {
            if let Ok(mut env) = vm.get_env() {
                android_fs::cache_main_activity_class(&mut env);
            }
            android_fs::set_java_vm(vm);
            log_info!("Android JNI_OnLoad: JavaVM registered");
            jni::sys::JNI_VERSION_1_6
        }
        Err(e) => {
            log_error!("Android JNI_OnLoad failed: {e}");
            jni::sys::JNI_ERR
        }
    }
}

